import uuid
from datetime import datetime
from pathlib import Path
from typing import Dict, Any, List
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

from app.config import settings
from app.models.job import ProcessingJob


class ExcelReportGenerator:
    """Generates styled, multi-section Excel reports (.xlsx) from approved job records."""

    def generate(self, job: ProcessingJob, user_name: str = "System") -> str:
        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = "Extracted Records"

        # Theme styling colors (Linear/DocuFlow Palette)
        header_fill = PatternFill(start_color="111827", end_color="111827", fill_type="solid")
        header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
        title_font = Font(name="Calibri", size=16, bold=True, color="111827")
        meta_label_font = Font(name="Calibri", size=10, bold=True, color="64748B")
        meta_val_font = Font(name="Calibri", size=10, color="111827")
        border_thin = Side(border_style="thin", color="E2E8F0")
        box_border = Border(left=border_thin, right=border_thin, top=border_thin, bottom=border_thin)

        # 1. Title Banner
        ws.merge_cells("A1:G1")
        ws["A1"] = "DocuFlow — Document Extraction & Validation Report"
        ws["A1"].font = title_font
        ws["A1"].alignment = Alignment(vertical="center")
        ws.row_dimensions[1].height = 32

        # 2. Metadata Block
        doc_name = job.document.original_filename if job.document else "N/A"
        ws["A3"] = "Processing Job ID:"
        ws["B3"] = f"#JOB-{job.id}"
        ws["D3"] = "Generated At:"
        ws["E3"] = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")

        ws["A4"] = "Source Document:"
        ws["B4"] = doc_name
        ws["D4"] = "Generated By:"
        ws["E4"] = user_name

        ws["A5"] = "Pipeline Engine:"
        ws["B5"] = job.processing_type
        ws["D5"] = "Job Status:"
        ws["E5"] = job.status.value

        for r in range(3, 6):
            ws[f"A{r}"].font = meta_label_font
            ws[f"B{r}"].font = meta_val_font
            ws[f"D{r}"].font = meta_label_font
            ws[f"E{r}"].font = meta_val_font

        # 3. Data Table Headers
        headers = [
            "Record #",
            "Invoice Number",
            "Date",
            "Due Date",
            "Company / Client",
            "Total Amount",
            "Currency",
            "Contact Email",
            "Confidence",
            "Validation Status"
        ]

        start_row = 7
        for col_idx, h in enumerate(headers, 1):
            cell = ws.cell(row=start_row, column=col_idx, value=h)
            cell.fill = header_fill
            cell.font = header_font
            cell.alignment = Alignment(horizontal="center" if "Status" in h or "#" in h else "left", vertical="center")
            cell.border = box_border
        ws.row_dimensions[start_row].height = 24

        # 4. Populate Extracted Rows
        row_idx = start_row + 1
        valid_count = 0
        warning_count = 0
        invalid_count = 0

        for rec in job.extracted_records:
            data = rec.extracted_data or {}
            ws.cell(row=row_idx, column=1, value=rec.record_number).alignment = Alignment(horizontal="center")
            ws.cell(row=row_idx, column=2, value=data.get("invoice_number", "—"))
            ws.cell(row=row_idx, column=3, value=data.get("invoice_date") or data.get("date", "—"))
            ws.cell(row=row_idx, column=4, value=data.get("due_date", "—"))
            ws.cell(row=row_idx, column=5, value=data.get("company_name", "—"))

            # Total amount as formatted number
            amt_cell = ws.cell(row=row_idx, column=6)
            try:
                amt_val = float(data.get("total_amount", 0))
                amt_cell.value = amt_val
                amt_cell.number_format = "#,##0.00"
            except (ValueError, TypeError):
                amt_cell.value = data.get("total_amount", "—")

            ws.cell(row=row_idx, column=7, value=data.get("currency", "USD"))
            ws.cell(row=row_idx, column=8, value=data.get("email", "—"))

            conf_cell = ws.cell(row=row_idx, column=9, value=f"{int(rec.confidence_score * 100)}%")
            conf_cell.alignment = Alignment(horizontal="center")

            # Status cell with conditional background
            status_cell = ws.cell(row=row_idx, column=10, value=rec.validation_status.value)
            status_cell.alignment = Alignment(horizontal="center")
            status_val = rec.validation_status.value
            if status_val == "VALID":
                status_cell.fill = PatternFill(start_color="DCFCE7", end_color="DCFCE7", fill_type="solid")
                status_cell.font = Font(name="Calibri", bold=True, color="15803D")
                valid_count += 1
            elif status_val == "WARNING":
                status_cell.fill = PatternFill(start_color="FEF3C7", end_color="FEF3C7", fill_type="solid")
                status_cell.font = Font(name="Calibri", bold=True, color="B45309")
                warning_count += 1
            else:
                status_cell.fill = PatternFill(start_color="FEE2E2", end_color="FEE2E2", fill_type="solid")
                status_cell.font = Font(name="Calibri", bold=True, color="B91C1C")
                invalid_count += 1

            for c in range(1, len(headers) + 1):
                ws.cell(row=row_idx, column=c).border = box_border

            ws.row_dimensions[row_idx].height = 20
            row_idx += 1

        # 5. Summary KPI block at bottom
        summary_row = row_idx + 2
        ws.cell(row=summary_row, column=1, value="Summary Statistics").font = Font(name="Calibri", size=12, bold=True)
        ws.cell(row=summary_row + 1, column=1, value=f"Total Records Extracted: {len(job.extracted_records)}")
        ws.cell(row=summary_row + 2, column=1, value=f"Valid Records: {valid_count}")
        ws.cell(row=summary_row + 3, column=1, value=f"Warnings: {warning_count}")
        ws.cell(row=summary_row + 4, column=1, value=f"Invalid / Missing: {invalid_count}")

        # 6. Auto-fit column widths and freeze header pane
        ws.freeze_panes = "A8"
        for col in ws.columns:
            max_len = 0
            col_letter = get_column_letter(col[0].column)
            for cell in col:
                val_str = str(cell.value or "")
                if len(val_str) > max_len and "\n" not in val_str:
                    max_len = len(val_str)
            ws.column_dimensions[col_letter].width = max(max_len + 3, 12)

        # Save to storage/reports
        filename = f"report_job_{job.id}_{uuid.uuid4().hex[:8]}.xlsx"
        report_path = settings.reports_path / filename
        wb.save(report_path)
        return str(report_path)
