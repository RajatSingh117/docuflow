import uuid
from datetime import datetime
from pathlib import Path
from reportlab.lib.pagesizes import letter, landscape
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

from app.config import settings
from app.models.job import ProcessingJob


class PDFReportGenerator:
    """Generates styled PDF reports from approved job records using ReportLab."""

    def generate(self, job: ProcessingJob, user_name: str = "System") -> str:
        filename = f"report_job_{job.id}_{uuid.uuid4().hex[:8]}.pdf"
        report_path = settings.reports_path / filename

        # Create landscape document for wide tabular representation
        doc = SimpleDocTemplate(
            str(report_path),
            pagesize=landscape(letter),
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            "DocuFlowTitle",
            parent=styles["Heading1"],
            fontSize=18,
            leading=22,
            textColor=colors.HexColor("#111827"),
            fontName="Helvetica-Bold"
        )
        subtitle_style = ParagraphStyle(
            "DocuFlowSubtitle",
            parent=styles["Normal"],
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#64748B"),
            fontName="Helvetica"
        )
        cell_style = ParagraphStyle(
            "DocuFlowCell",
            parent=styles["Normal"],
            fontSize=8.5,
            leading=11,
            textColor=colors.HexColor("#111827"),
            fontName="Helvetica"
        )
        header_cell_style = ParagraphStyle(
            "DocuFlowHeaderCell",
            parent=styles["Normal"],
            fontSize=8.5,
            leading=11,
            textColor=colors.white,
            fontName="Helvetica-Bold"
        )

        story = []

        # 1. Header Banner
        story.append(Paragraph("DocuFlow — Document Processing & Validation Report", title_style))
        story.append(Paragraph("Automated extraction summary and human-in-the-loop audit sign-off.", subtitle_style))
        story.append(Spacer(1, 10))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#E2E8F0"), spaceAfter=14))

        # 2. Metadata Grid
        doc_name = job.document.original_filename if job.document else "N/A"
        meta_data = [
            [
                Paragraph("<b>Processing Job ID:</b>", subtitle_style),
                Paragraph(f"#JOB-{job.id}", cell_style),
                Paragraph("<b>Generated Timestamp:</b>", subtitle_style),
                Paragraph(datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC"), cell_style)
            ],
            [
                Paragraph("<b>Source Document:</b>", subtitle_style),
                Paragraph(doc_name, cell_style),
                Paragraph("<b>Generated By:</b>", subtitle_style),
                Paragraph(user_name, cell_style)
            ],
            [
                Paragraph("<b>Pipeline Type:</b>", subtitle_style),
                Paragraph(job.processing_type, cell_style),
                Paragraph("<b>Processing Status:</b>", subtitle_style),
                Paragraph(job.status.value, cell_style)
            ]
        ]
        meta_table = Table(meta_data, colWidths=[120, 240, 130, 240])
        meta_table.setStyle(TableStyle([
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(meta_table)
        story.append(Spacer(1, 16))

        # 3. Extracted Records Table
        table_headers = [
            Paragraph("Rec #", header_cell_style),
            Paragraph("Invoice No", header_cell_style),
            Paragraph("Date", header_cell_style),
            Paragraph("Due Date", header_cell_style),
            Paragraph("Company / Client", header_cell_style),
            Paragraph("Total Amount", header_cell_style),
            Paragraph("Email", header_cell_style),
            Paragraph("Confidence", header_cell_style),
            Paragraph("Status", header_cell_style),
        ]

        table_rows = [table_headers]

        for rec in job.extracted_records:
            data = rec.extracted_data or {}
            table_rows.append([
                Paragraph(str(rec.record_number), cell_style),
                Paragraph(data.get("invoice_number", "—"), cell_style),
                Paragraph(data.get("invoice_date") or data.get("date", "—"), cell_style),
                Paragraph(data.get("due_date", "—"), cell_style),
                Paragraph(data.get("company_name", "—"), cell_style),
                Paragraph(f"{data.get('currency', 'USD')} {data.get('total_amount', '0.00')}", cell_style),
                Paragraph(data.get("email", "—"), cell_style),
                Paragraph(f"{int(rec.confidence_score * 100)}%", cell_style),
                Paragraph(f"<b>{rec.validation_status.value}</b>", cell_style)
            ])

        records_table = Table(table_rows, colWidths=[45, 90, 80, 80, 140, 95, 110, 60, 60])
        records_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#111827")),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('ALIGN', (0, 0), (0, -1), 'CENTER'),
            ('ALIGN', (7, 0), (8, -1), 'CENTER'),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ]))
        story.append(records_table)
        story.append(Spacer(1, 18))

        # 4. Summary & Verification Footnote
        summary_text = (
            f"<b>Summary:</b> Total Records Extracted: {len(job.extracted_records)} • "
            f"Processing Duration: {job.processing_duration or 0}s • "
            "Verified and certified under DocuFlow Document Processing Platform."
        )
        story.append(Paragraph(summary_text, subtitle_style))

        # Build document
        doc.build(story)
        return str(report_path)
